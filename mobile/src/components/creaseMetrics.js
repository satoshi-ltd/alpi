const WIDE = 1.05;
const SAFETY = 1.02;

export function creaseWidth(text, size) {
  let em = 0;
  for (const ch of String(text ?? '')) {
    const code = ch.codePointAt(0);
    em += code >= 32 && code < 127 ? ASCII[code - 32] : WIDE;
  }
  return Math.ceil(em * size * SAFETY);
}
