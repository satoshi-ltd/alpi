// Deterministic bridge: assets.yaml → content + public/img. Runs as the first
// step of `npm run ship` (no-op when there's no manifest). Replaces the old
// LLM-driven wiring (Quill editing JSON + Pixel optimising by hand), which
// failed intermittently once a manifest had many slots. Muse produces images +
// manifest; this materialises every raster to /img/<basename>.webp and writes
// the slot into every locale JSON. Quill no longer routes assets; Pixel just
// runs ship. Exits non-zero with a clear reason on a missing source file.
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync, copyFileSync, rmSync } from "node:fs";
import { join, basename, extname } from "node:path";

const MANIFEST = "assets/assets.yaml";
const CONTENT = "src/content";
const OUT = "public/img";

if (!existsSync(MANIFEST)) {
  console.log("apply-assets-manifest: no assets.yaml — nothing to wire");
  process.exit(0);
}

// v1 scope: Muse is brand-critical only. We wire the hero + an optional small
// home gallery, and materialise the logo. Specific room/dining/amenity slots are
// intentionally NOT supported — that imagery stays a tonal placeholder until a
// real photo is supplied. Unsupported slots are ignored (never materialised), so
// they can't become orphans; Quill's stray paths are dropped by the sweep below.
const SUPPORTED = new Set(["home.hero.image", "home.gallery[]", "brand.logo"]);
// Inventory slots open ONLY to restored real photos — fabricated inventory stays impossible.
const RESTORED_COLLECTIONS = new Set(["rooms", "dining", "amenities", "experiences"]);
const slotAllowed = (e) => {
  if (SUPPORTED.has(e.slot)) return true;
  const m = (e.slot || "").match(/^(\w+)\.([\w-]+)\.image$/);
  return !!m && RESTORED_COLLECTIONS.has(m[1]) && e.kind === "restored";
};
const field = (block, key) =>
  (block.match(new RegExp(`(?:^|\\n)\\s*${key}:\\s*["']?([^"'\\n]+?)["']?\\s*$`, "m")) || [])[1];
const all = readFileSync(MANIFEST, "utf8")
  .split(/\n(?=- )/).map((b) => b.trim()).filter(Boolean)
  .map((b) => ({ file: field(b, "file"), kind: field(b, "kind"), slot: field(b, "slot") }))
  .filter((e) => e.file && e.slot);
// Warn (don't fail) on out-of-scope slots so a Muse regression is visible, not silent.
for (const e of all.filter((e) => !slotAllowed(e))) {
  console.warn(`apply-assets-manifest: unsupported slot ignored: ${e.slot} (${e.file}) — inventory slots accept kind: restored only`);
}
const entries = all.filter(slotAllowed);

const errors = [];
let sharp = null;
const written = new Set(); // public/img files this run owns

mkdirSync(OUT, { recursive: true });
for (const e of entries) {
  if (!existsSync(e.file)) { errors.push(`manifest file missing on disk: ${e.file}`); continue; }
  const stem = basename(e.file, extname(e.file));
  if (extname(e.file).toLowerCase() === ".svg") {
    copyFileSync(e.file, join(OUT, `${stem}.svg`));
    written.add(`${stem}.svg`);
    e.ref = `/img/${stem}.svg`;
    continue;
  }
  e.ref = `/img/${stem}.webp`;
  if (!sharp) sharp = (await import("sharp")).default; // astro's transitive dep
  await sharp(e.file).webp({ quality: 82 }).toFile(join(OUT, `${stem}.webp`));
  written.add(`${stem}.webp`);
}
if (errors.length) { console.error("apply-assets-manifest FAIL:"); errors.forEach((x) => console.error("  - " + x)); process.exit(1); }

// CONTRACT: assets.yaml owns public/img. Every served image must enter through
// the manifest (generated by Muse, or a real supplied photo listed there) — this
// drops any raster not written this run, so a re-run leaves exactly the manifest
// set and no stale orphan lingers. A real photo dropped straight into public/img
// without a manifest entry WILL be deleted; list it in assets.yaml instead.
(function prune(dir) {
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, ent.name);
    if (ent.isDirectory()) { prune(p); continue; }
    if (/\.(webp|avif|jpe?g|png|gif|svg)$/i.test(ent.name) && !written.has(ent.name)) rmSync(p);
  }
})(OUT);

function parseSlot(slot) {
  const arr = slot.endsWith("[]");
  const t = (arr ? slot.slice(0, -2) : slot).split(".");
  if (t[0] === "home") return { dir: "pages", base: "home", path: t.slice(1), arr };
  if (RESTORED_COLLECTIONS.has(t[0]) && t.length === 3 && t[2] === "image")
    return { dir: t[0], base: t[1], path: ["image"], arr: false };
  return null;
}
const localeFiles = (dir, base) => {
  const d = join(CONTENT, dir);
  return existsSync(d) ? readdirSync(d).filter((f) => f.startsWith(base + ".") && f.endsWith(".json")).map((f) => join(d, f)) : [];
};
const setPath = (obj, path, value) => {
  let o = obj;
  for (let i = 0; i < path.length - 1; i++) { o[path[i] ??= {}] ??= {}; o = o[path[i]]; }
  o[path[path.length - 1]] = value;
};
const writeJson = (fp, j) => writeFileSync(fp, JSON.stringify(j, null, 2) + "\n");

const galleries = new Map(); // (dir|base|path) → {dir, base, path, files, refs}
const SITE = "src/config/site.json";
for (const e of entries) {
  if (!e.ref) continue;
  if (e.slot === "brand.logo") {
    const j = JSON.parse(readFileSync(SITE, "utf8"));
    j.brand = { ...j.brand, logo: e.ref };
    writeJson(SITE, j);
    continue;
  }
  const s = parseSlot(e.slot);
  if (!s) continue;
  const files = localeFiles(s.dir, s.base);
  if (!files.length) { errors.push(`slot ${e.slot}: no content files at ${s.dir}/${s.base}.*.json`); continue; }
  if (s.arr) {
    const key = [s.dir, s.base, s.path.join(".")].join("|");
    (galleries.get(key) ?? galleries.set(key, { s, files, refs: [] }).get(key)).refs.push(e.ref);
  } else {
    for (const fp of files) { const j = JSON.parse(readFileSync(fp, "utf8")); setPath(j, s.path, e.ref); writeJson(fp, j); }
  }
}
for (const { s, files, refs } of galleries.values()) {
  for (const fp of files) { const j = JSON.parse(readFileSync(fp, "utf8")); setPath(j, s.path, refs.slice()); writeJson(fp, j); }
}

// The manifest owns every `/img/` reference: sweep all content and drop any
// dangling path Quill wrote without a materialised file behind it (a stale
// `about.image`/`location.map` left in some locales = a dead <img> otherwise).
const owned = new Set([...written].map((n) => `/img/${n}`));
const sweep = (node) => {
  if (Array.isArray(node)) return node.filter((v) => !(typeof v === "string" && v.startsWith("/img/") && !owned.has(v))).map(sweep);
  if (node && typeof node === "object") {
    for (const k of Object.keys(node)) {
      const v = node[k];
      if (typeof v === "string" && v.startsWith("/img/") && !owned.has(v)) delete node[k];
      else node[k] = sweep(v);
    }
  }
  return node;
};
(function walkJson(dir) {
  if (!existsSync(dir)) return;
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, ent.name);
    if (ent.isDirectory()) walkJson(p);
    else if (ent.name.endsWith(".json")) writeJson(p, sweep(JSON.parse(readFileSync(p, "utf8"))));
  }
})(CONTENT);

if (errors.length) { console.error("apply-assets-manifest FAIL:"); errors.forEach((x) => console.error("  - " + x)); process.exit(1); }
console.log(`apply-assets-manifest OK · ${entries.length} assets materialised + wired across locales`);
